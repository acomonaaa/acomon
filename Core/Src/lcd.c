void LCD_ShowChar(uint16_t x, uint16_t y, uint8_t chr, uint16_t color)
{
    uint8_t c = chr - ' ';
    uint8_t i, j;
    for (i = 0; i < 16; i++) {
        uint8_t line = ascii_8x16[c][i];
        for (j = 0; j < 8; j++) {
            if (line & (0x80 >> j)) {
                LCD_DrawPoint(x + j, y + i, color);
            }
        }
    }
}

void LCD_ShowString(uint16_t x, uint16_t y, uint16_t width, uint16_t height, uint8_t size, uint8_t *str)
{
    uint8_t x0 = x;
    uint16_t i, w;
    uint16_t max_w = width / 8;

    if (size != 16) return;

    while (*str != '\0') {
        w = 1;
        if (x + w * 8 > x0 + width) {
            x = x0;
            y += 16;
        }
        if (y + 16 > height) break;
        LCD_ShowChar(x, y, *str, COLOR_RED);
        x += 8;
        str++;
    }
}

